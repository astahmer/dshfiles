#!/usr/bin/env node

/**
 * Cached browser checks: builds the selected owners' boot closure once, then runs the per-package Turbo tasks so a
 * package whose built bundles, journeys and harness did not change replays from the shared Turbo cache. A named
 * selection builds and digests only its own closure; a broad invocation still builds every owned bundle.
 *
 * Journeys run one at a time; the boot gate overlaps three checks off CI (`CHECK_BROWSER_CONCURRENCY` overrides
 * either). A broad journey run refuses to start without `--all`: `node --run check:e2e workbench` silently drops the
 * argument, so a scoped intention becomes every journey in the repository, and a measured 50-minute run started that
 * way. Names also come from `DSHX_E2E_ONLY`, which no argument path can lose.
 *
 *   node scripts/check-browser.mjs e2e   [plugin|feature ...] [--all] [--force]   journeys      (pnpm check:e2e)
 *   node scripts/check-browser.mjs smoke [plugin|feature ...]         [--force]   @smoke subset (pnpm check:e2e:smoke)
 *   node scripts/check-browser.mjs boot  [plugin ...]                 [--force]   boot checks   (pnpm check:plugin-boot)
 *
 * Task inputs are generated by tooling/dshx/scripts/browser-tasks.mjs. `--force` ignores the cache and reruns all.
 */

import { spawn, spawnSync } from 'node:child_process'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveBrowserSelection, writeDistDigests } from '../tooling/dshx/scripts/browser-tasks.mjs'
import { reapRecordedScratchProcesses, scratchLedgerPath } from '../tooling/dshx/scripts/reap-scratch-processes.mjs'
import { turboCacheDir } from './turbo-cache.mjs'

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tasks = { e2e: 'test:e2e', smoke: 'test:e2e:smoke', boot: 'test:boot' }
const [mode, ...rest] = process.argv.slice(2)
const task = tasks[mode]
const flagNames = new Set(['--force', '--all'])
const usage = `Usage: node scripts/check-browser.mjs <${Object.keys(tasks).join('|')}> [plugin|feature ...] [--all] [--force]`
if (task === undefined) {
  console.error(usage)
  process.exit(2)
}
const force = rest.includes('--force')
const acknowledged = rest.includes('--all') || !['', '0', 'false'].includes(process.env.DSHX_E2E_ALL ?? '')
const envNames = (process.env.DSHX_E2E_ONLY ?? '').split(/[\s,]+/).filter(Boolean)
const names = [...rest.filter(argument => !flagNames.has(argument)), ...envNames]
const inCi = !['', '0', 'false'].includes(process.env.CI ?? '')
const broadJourneys = mode === 'e2e' && names.length === 0
if (broadJourneys && !inCi && !acknowledged) {
  console.error(
    [
      'check-browser e2e: refusing to run every journey in the repository.',
      '',
      'Name the plugin or feature you are iterating — one owner replays the other 42 tasks from cache:',
      '  pnpm run check:e2e workbench',
      '  DSHX_E2E_ONLY=workbench node --run check:e2e    # node --run forwards arguments only after `--`',
      '',
      'A merge or a cross-plugin change that really needs all of them (~30-50 minutes, and the cache only replays what',
      'did not change):',
      '  pnpm run check:e2e --all',
    ].join('\n'),
  )
  process.exit(2)
}
const forcedByEnv = !['', '0', 'false'].includes(process.env.TURBO_FORCE ?? '')
if (force || forcedByEnv) {
  console.log(
    `check-browser ${mode}: ${force ? '--force' : 'TURBO_FORCE'} ignores the Turbo cache, so this reruns every selected journey instead of ` +
      'replaying an unchanged one. Use it only when a binary outside the repository changed (other than jj), or once before landing — while ' +
      'iterating one plugin, run its scoped check without it.',
  )
}
// Journeys stay serial (parallel Host plus Chromium boots make them flaky under load); the boot gate asserts a mount
// and runs no journey, so three at a time measured ~2.7x faster on ten cores.
const concurrency = process.env.CHECK_BROWSER_CONCURRENCY ?? (mode === 'boot' && !inCi ? '3' : '1')
// A broad local journey run stops at the first red owner instead of paying for every remaining owner to fail, and
// bounds Playwright's own failure list. CI and `DSHX_E2E_KEEP_GOING=1` still report the whole picture.
const keepGoing = !broadJourneys || inCi || !['', '0', 'false'].includes(process.env.DSHX_E2E_KEEP_GOING ?? '')
const maxFailures = process.env.DSHX_E2E_MAX_FAILURES ?? (broadJourneys && !inCi ? '3' : '')

// Reap what a previous run in this workspace recorded and never stopped. A live `dshx dev up` Host has the same
// profile and no parent either, so the ledger — not the command line — decides what is ours to kill.
const scratchLedger = scratchLedgerPath(workspaceRoot)
const reaped = await reapRecordedScratchProcesses({ ledgerPath: scratchLedger })
if (reaped.length > 0) {
  console.log(
    `check-browser ${mode}: reaped ${String(reaped.length)} leaked scratch Host(s) a killed run left behind (pid ${reaped.map(entry => String(entry.pid)).join(', ')})`,
  )
}

const { filters, buildTargets } = await resolveBrowserSelection({ names, mode })

const jj = spawnSync('jj', ['--version'], { encoding: 'utf8' })
const toolVersions = jj.status === 0 ? jj.stdout.trim() : 'jj unavailable'

const turboCache = turboCacheDir()
console.log(
  `check-browser ${mode}: ${names.length === 0 ? 'every owner' : names.join(', ')} — concurrency ${concurrency}${force ? ', forced' : ''}, cache ${turboCache}`,
)

const turbo = (args, env = {}) =>
  new Promise((resolveRun, reject) => {
    const child = spawn('pnpm', ['exec', 'turbo', 'run', ...args], {
      cwd: workspaceRoot,
      stdio: 'inherit',
      env: { ...process.env, ...env, TURBO_CACHE_DIR: turboCache },
    })
    child.once('error', reject)
    child.once('close', code => resolveRun(code ?? 1))
  })

// Generate the 48 BDD specs once for the whole run: each owner task regenerating them measured 3.6-4.8s, ~2.6 minutes of
// a broad run, for identical output. `DSHX_E2E_GENERATED=1` tells every task they are already there.
const generateSpecs = () =>
  new Promise((resolveRun, reject) => {
    const child = spawn('pnpm', ['exec', 'bddgen', 'test', '--config=playwright.e2e.config.ts'], {
      cwd: resolve(workspaceRoot, 'tooling/dshx'),
      stdio: 'inherit',
    })
    child.once('error', reject)
    child.once('close', code => resolveRun(code ?? 1))
  })

const startedAt = Date.now()
// A named selection builds only its own boot closure (Turbo still resolves shared dependencies through `^build`);
// a broad invocation keeps building every owned bundle.
const buildFilters = buildTargets === undefined ? ['--filter=./plugins/@dshfiles/*', '--filter=@dshfiles/dshx'] : buildTargets.map(name => `--filter=${name}`)
const built = await turbo(['build', ...buildFilters, '--output-logs=errors-only'])
if (built !== 0) process.exit(built)
await writeDistDigests(buildTargets === undefined ? {} : { names: buildTargets })
if (mode === 'boot') {
  const ignores = spawnSync(process.execPath, ['tooling/dshx/scripts/boot-check-web.mjs', '--validate-ignores'], { cwd: workspaceRoot, stdio: 'inherit' })
  if (ignores.status !== 0) process.exit(ignores.status ?? 1)
} else {
  const generated = await generateSpecs()
  if (generated !== 0) process.exit(generated)
}
const taskEnvironment = { DSHX_TOOL_VERSIONS: toolVersions }
if (mode !== 'boot') taskEnvironment.DSHX_E2E_GENERATED = '1'
if (maxFailures !== '') taskEnvironment.DSHX_E2E_MAX_FAILURES = maxFailures
const status = await turbo(
  [task, ...filters, `--concurrency=${concurrency}`, ...(keepGoing ? ['--continue'] : []), '--output-logs=new-only', ...(force ? ['--force'] : [])],
  taskEnvironment,
)
// An aborted Turbo run can leave the scratch Host of the task it killed: Turbo has returned, so nothing in this
// workspace is mid-run and the floor drops to zero.
await reapRecordedScratchProcesses({ ledgerPath: scratchLedger, minAgeMs: 0 })
console.log(
  `check-browser ${mode}: ${status === 0 ? 'passed' : 'failed'} in ${String(Math.round((Date.now() - startedAt) / 1000))}s (cache ${turboCache}, concurrency ${concurrency})`,
)
process.exitCode = status
