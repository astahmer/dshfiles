#!/usr/bin/env node

/**
 * Cached browser checks: builds every bundle once, then runs the per-package Turbo tasks one at a time, so a package
 * whose built bundles, journeys and harness did not change replays from the local Turbo cache.
 *
 *   node scripts/check-browser.mjs e2e   [plugin|feature ...] [--force]   journeys      (pnpm check:e2e)
 *   node scripts/check-browser.mjs smoke [plugin|feature ...] [--force]   @smoke subset (pnpm check:e2e:smoke)
 *   node scripts/check-browser.mjs boot  [plugin ...]         [--force]   boot checks   (pnpm check:plugin-boot)
 *
 * Task inputs are generated by tooling/dshx/scripts/browser-tasks.mjs. `--force` ignores the cache and reruns all.
 */

import { spawn, spawnSync } from 'node:child_process'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { planBrowserTasks, writeDistDigests } from '../tooling/dshx/scripts/browser-tasks.mjs'

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tasks = { e2e: 'test:e2e', smoke: 'test:e2e:smoke', boot: 'test:boot' }
const [mode, ...rest] = process.argv.slice(2)
const task = tasks[mode]
if (task === undefined) {
  console.error(`Usage: node scripts/check-browser.mjs <${Object.keys(tasks).join('|')}> [plugin|feature ...] [--force]`)
  process.exit(2)
}
const force = rest.includes('--force')
const names = rest.filter(argument => argument !== '--force')

const { owners } = await planBrowserTasks()
const packageFor = name => {
  if (name.startsWith('@dshfiles/') || name === 'dshfiles-plugins') return name
  const featureOwner = [...owners.values()].find(owner => owner.features.includes(name))
  if (mode !== 'boot' && featureOwner !== undefined) return featureOwner.name
  return `@dshfiles/${name}`
}
const filters = names.length === 0 ? ['--filter=./plugins', '--filter=./plugins/@dshfiles/*'] : names.map(name => `--filter=${packageFor(name)}`)

const jj = spawnSync('jj', ['--version'], { encoding: 'utf8' })
const toolVersions = jj.status === 0 ? jj.stdout.trim() : 'jj unavailable'

const turbo = (args, env = {}) =>
  new Promise((resolveRun, reject) => {
    const child = spawn('pnpm', ['exec', 'turbo', 'run', ...args], { cwd: workspaceRoot, stdio: 'inherit', env: { ...process.env, ...env } })
    child.once('error', reject)
    child.once('close', code => resolveRun(code ?? 1))
  })

const startedAt = Date.now()
const built = await turbo(['build', '--filter=./plugins/@dshfiles/*', '--filter=@dshfiles/dshx', '--output-logs=errors-only'])
if (built !== 0) process.exit(built)
await writeDistDigests()
if (mode === 'boot') {
  const ignores = spawnSync(process.execPath, ['tooling/dshx/scripts/boot-check-web.mjs', '--validate-ignores'], { cwd: workspaceRoot, stdio: 'inherit' })
  if (ignores.status !== 0) process.exit(ignores.status ?? 1)
}
// One browser task at a time: each boots a Host and a Chromium, and parallel boots make journeys flaky under load.
const status = await turbo([task, ...filters, '--concurrency=1', '--continue', '--output-logs=new-only', ...(force ? ['--force'] : [])], {
  DSHX_TOOL_VERSIONS: toolVersions,
})
console.log(`check-browser ${mode}: ${status === 0 ? 'passed' : 'failed'} in ${String(Math.round((Date.now() - startedAt) / 1000))}s`)
process.exitCode = status
