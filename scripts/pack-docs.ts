import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import type { CatalogFeature, Prerequisite } from '../plugins/@dshfiles/onboarding/src/catalog-model.ts'
import { curationOf } from '../plugins/@dshfiles/onboarding/src/curation.ts'
import { FEATURE_CATALOG } from '../plugins/@dshfiles/onboarding/src/generated/feature-catalog.ts'
import { PACKS, type Pack } from '../plugins/@dshfiles/onboarding/src/packs.ts'

/**
 * Write `docs/packs/<pack>.md` and its index from the one pack definition (`onboarding/src/packs.ts`) and the onboarding
 * feature catalog. `--check` writes nothing and fails when a page is missing, stale or no longer generated.
 * Usage: node scripts/pack-docs.ts [--check] [--out <dir>]
 */

const repositoryRoot = join(import.meta.dirname, '..')
const header =
  '<!-- Generated by scripts/pack-docs.ts from plugins/@dshfiles/onboarding/src/packs.ts and the onboarding feature catalog. Run `node scripts/pack-docs.ts`; never edit by hand. -->'

const prerequisiteLabels = {
  account: 'An AI account is configured.',
  project: 'A project is added.',
  repository: 'The project is a jj or git repository.',
  github: 'The GitHub CLI is signed in (`gh auth login`).',
} satisfies Record<Prerequisite, string>

const isCurated = (feature: CatalogFeature): boolean => curationOf({ feature, features: FEATURE_CATALOG.features }).curated

const description = (plugin: string): string => {
  const entry = FEATURE_CATALOG.plugins.find(candidate => candidate.name === plugin)
  if (entry === undefined)
    throw new Error(`Pack plugin ${plugin} is not in the onboarding feature catalog; run pnpm --dir plugins/@dshfiles/onboarding generate.`)
  return entry.description
}

const featureLine = (feature: CatalogFeature, index: number): string =>
  `${String(index + 1)}. **${feature.title}** (\`${feature.plugin}\`${feature.destination === 'none' ? '' : `, ${feature.destination}`}) — ${feature.summary}`

const featureSection = (pack: Pack): readonly string[] => {
  const features = pack.plugins.flatMap(plugin => FEATURE_CATALOG.features.filter(feature => feature.plugin === plugin))
  const curated = features.filter(isCurated)
  const more = features.filter(feature => !isCurated(feature))
  return [
    '## Features',
    '',
    `From the onboarding feature catalog: ${String(features.length)} features, the ${String(curated.length)} curated ones first.`,
    '',
    ...(curated.length === 0 ? [] : ['### Curated', '', ...curated.map(featureLine), '']),
    ...(more.length === 0 ? [] : ['### More', '', ...more.map(featureLine), '']),
  ]
}

const enableSection = (pack: Pack): readonly string[] => {
  const shell = pack.core ? 'dshx init --profile <name> --packs core' : `dshx init --profile <name> --packs ${pack.id}`
  return [
    '## Enable it',
    '',
    ...(pack.core
      ? [
          'Core is always on: Getting started offers no Enable or Disable for it, `onboarding_pack_apply` never disables it, and `dshx init` composes it into every profile.',
          '',
        ]
      : [
          `1. In the app: **Knowledge › Getting started**, then **Enable pack** on ${pack.title} under Packs. It previews exactly what changes; **Disable pack** reverses it.`,
          `2. From an Agent: the \`onboarding_pack_apply\` tool with pack \`${pack.id}\`. It runs only when you ask, after showing the preview.`,
          `3. From a shell: \`${shell}\` (Core is added; \`--dry-run\` previews). See [\`dshx init\`](../../tooling/dshx/docs/cli-reference.md#dshx-init-compose-a-profile-from-packs).`,
          '',
        ]),
    ...(pack.core ? [`To compose a new profile with Core only: \`${shell}\`.`, ''] : []),
  ]
}

const restartSection: readonly string[] = [
  '## Restart',
  '',
  'Installing a plugin the profile does not have yet needs a DSH Host restart: DSH reads the profile once at boot. Plugins already installed are switched on in the running DSH. Nothing restarts on its own: use **Restart when idle** in the sidebar when DSH runs under the managed launcher, otherwise your own launcher.',
  '',
]

const renderPack = (pack: Pack): string =>
  [
    header,
    '',
    `# ${pack.title}`,
    '',
    pack.summary,
    '',
    `Pack id \`${pack.id}\`${pack.core ? ', always on: every other pack builds on it' : ''}. Back to [all packs](README.md).`,
    '',
    '## Plugins',
    '',
    ...pack.plugins.map(
      (plugin, index) => `${String(index + 1)}. [\`@dshfiles/${plugin}\`](../../plugins/@dshfiles/${plugin}/README.md) — ${description(plugin)}`,
    ),
    '',
    '## Prerequisites',
    '',
    ...(pack.prerequisites.length === 0
      ? ['None.']
      : pack.prerequisites.map((prerequisite, index) => `${String(index + 1)}. ${prerequisiteLabels[prerequisite]}`)),
    '',
    '## Key settings',
    '',
    ...(pack.keySettings.length === 0
      ? ['None.']
      : pack.keySettings.map(
          (setting, index) => `${String(index + 1)}. **${setting.label}**: Settings entry \`${setting.entryId}\`, field \`${setting.fieldPath.join('.')}\`.`,
        )),
    '',
    ...featureSection(pack),
    ...enableSection(pack),
    ...restartSection,
  ].join('\n')

const renderIndex = (): string =>
  [
    header,
    '',
    '# Plugin packs',
    '',
    "A pack is a named set of owned plugins adopted together; a plugin may sit in several. Getting started (**Knowledge › Getting started**) shows the same packs with each plugin's live state, `onboarding_pack_apply` enables or disables one, and `dshx init` composes a new profile from them. Core is always on.",
    '',
    ...PACKS.map(
      (pack, index) => `${String(index + 1)}. [${pack.title}](${pack.id}.md) (\`${pack.id}\`, ${String(pack.plugins.length)} plugins) — ${pack.summary}`,
    ),
    '',
  ].join('\n')

const pages = (): ReadonlyMap<string, string> =>
  new Map<string, string>([['README.md', renderIndex()], ...PACKS.map((pack): [string, string] => [`${pack.id}.md`, renderPack(pack)])])

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false }, out: { type: 'string' } } })
const outDirectory = resolve(values.out ?? join(repositoryRoot, 'docs/packs'))
const expected = pages()
const present = existsSync(outDirectory) ? readdirSync(outDirectory).filter(file => file.endsWith('.md')) : []
const extra = present.filter(file => !expected.has(file))
const stale = [...expected]
  .filter(([file, content]) => !existsSync(join(outDirectory, file)) || readFileSync(join(outDirectory, file), 'utf8') !== content)
  .map(([file]) => file)

if (values.check) {
  if (stale.length === 0 && extra.length === 0) console.log(`pack-docs: ${String(expected.size)} pages up to date`)
  else {
    for (const file of stale) console.error(`pack-docs: ${file} is missing or stale`)
    for (const file of extra) console.error(`pack-docs: ${file} is not generated from any pack`)
    console.error('pack-docs: run `node scripts/pack-docs.ts` and commit docs/packs.')
    process.exitCode = 1
  }
} else {
  mkdirSync(outDirectory, { recursive: true })
  for (const file of stale) writeFileSync(join(outDirectory, file), expected.get(file) ?? '')
  for (const file of extra) rmSync(join(outDirectory, file))
  console.log(`pack-docs: wrote ${String(stale.length)}, removed ${String(extra.length)}, ${String(expected.size)} pages in ${outDirectory}`)
}
