#!/usr/bin/env node
/**
 * Rasterize `assets/mark.svg` into the PNG icons the manifest and iOS need, and
 * write them into `src/icons.generated.ts` as base64 so the Host bundle carries
 * its own artwork (no runtime file reads, no build-time asset copy).
 *
 *   pnpm --dir plugins/@dshfiles/pwa icons
 */
import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'

const requireFromDshx = createRequire(new URL('../../../../tooling/dshx/packages/dshx/package.json', import.meta.url))
const { chromium } = requireFromDshx('playwright')

const BACKGROUND = '#0f1115'
const MARK = await readFile(new URL('../assets/mark.svg', import.meta.url), 'utf8')

const icons = [
  { name: 'icon-192.png', size: 192, markWidth: 0.66 },
  { name: 'icon-512.png', size: 512, markWidth: 0.66 },
  { name: 'icon-maskable-512.png', size: 512, markWidth: 0.52 },
  { name: 'apple-touch-icon-180.png', size: 180, markWidth: 0.66 },
]

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage()

const dataUrls = await page.evaluate(
  async ({ background, mark, icons }) => {
    const image = new Image()
    image.src = `data:image/svg+xml;base64,${btoa(mark)}`
    await image.decode()
    const rendered = {}
    for (const { name, size, markWidth } of icons) {
      const canvas = document.createElement('canvas')
      canvas.width = size
      canvas.height = size
      const context = canvas.getContext('2d')
      context.fillStyle = background
      context.fillRect(0, 0, size, size)
      const width = size * markWidth
      const height = (width * image.naturalHeight) / image.naturalWidth
      context.drawImage(image, (size - width) / 2, (size - height) / 2, width, height)
      rendered[name] = { size, dataUrl: canvas.toDataURL('image/png') }
    }
    return rendered
  },
  { background: BACKGROUND, mark: MARK, icons },
)

await browser.close()

const entries = Object.entries(dataUrls).map(([name, { size, dataUrl }]) => {
  const [prefix, base64] = dataUrl.split(',')
  if (prefix !== 'data:image/png;base64' || base64 === undefined) throw new Error(`${name} did not encode as PNG`)
  return { name, size, base64 }
})

const body = entries.map(({ name, base64 }) => `  '${name}':\n    '${base64}',`).join('\n')
const file = `/**
 * Generated by scripts/generate-icons.mjs from assets/mark.svg: ${entries.map(entry => `${entry.name} ${entry.size}px`).join(', ')}.
 * Regenerate with \`pnpm --dir plugins/@dshfiles/pwa icons\` instead of editing.
 */
export const iconAssets = {
${body}
} as const

export type IconName = keyof typeof iconAssets

export const iconNames: readonly IconName[] = [${entries.map(({ name }) => `'${name}'`).join(', ')}]

export const isIconName = (value: string): value is IconName => Object.hasOwn(iconAssets, value)
`
await writeFile(new URL('../src/icons.generated.ts', import.meta.url), file)
const total = entries.reduce((sum, entry) => sum + entry.base64.length, 0)
console.log(`wrote ${entries.length} icons (${Math.round(total / 1024)} KB base64) into src/icons.generated.ts`)
