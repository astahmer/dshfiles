#!/usr/bin/env node

/**
 * Plans the cached browser tasks: one `test:e2e` (and `test:e2e:smoke`) per package that owns feature files, one
 * `test:boot` per bundle and the composed web-profile boot, each with every input it reads spelled out, and writes
 * them as package-level `turbo.json` files plus the package scripts that run them.
 *
 * Inputs are the built `dist` of every bundle a task boots and of dshx itself, never the build task's hash and never
 * the sources behind it: source maps and declarations stay out, so a formatting-only edit that keeps a bundle's
 * JavaScript byte-identical leaves its tasks cached, and a dshx source edit that compiles to the same JavaScript must
 * leave them cached too. A new utility class in any plugin is the opposite case: it changes that plugin's own
 * JavaScript and the union sheet that only @dshfiles/ui-styles compiles, so the owner's digest and the owning
 * plugin's digest move while every other consumer bundle stays byte-identical.
 * A journey that boots a plugin-ui consumer also reads the owner's digest, because a sheet change can change what it
 * asserts, while the per-bundle boot check stays isolated and never reads it.
 * Turbo drops gitignored files under the task's own package directory even from a `$TURBO_ROOT$` glob (a package
 * would not see its own `dist`, and the `plugins` workspace no bundle's), so `writeDistDigests` records each
 * package's runtime `dist` (no source maps or declarations) under the root `.turbo/browser-dist/`, and tasks key on
 * those files. Callers build and write the digests first, as root `scripts/check-browser.mjs` does.
 */

import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync } from 'node:fs'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const dshxRoot = 'tooling/dshx'
const featuresDir = `${dshxRoot}/e2e/features`
const supportDir = `${dshxRoot}/e2e/support`
const journeysDir = `${supportDir}/plugin-journeys`
const crossPluginOwner = 'dshfiles-plugins'
/** The one bundle that compiles the shared plugin-ui sheet; a composed boot of a consumer loads it too. */
const sharedStylesBundle = '@dshfiles/ui-styles'
const distDigestDir = '.turbo/browser-dist'
const distDigestFile = name => `${distDigestDir}/${name.replace(/^@/, '').replace(/\//g, '__')}.sha256`
const generatedNotice = '// Generated by tooling/dshx/scripts/browser-tasks.mjs --write; change that script, not this file.'

/** Read by every browser task: its runtime pins and the seed the scratch profiles copy. */
const sharedInputs = [`${dshxRoot}/package.json`, `${dshxRoot}/scripts/browser-tasks.mjs`, 'pnpm-lock.yaml', 'profiles/web/**']
/** Read by the journeys only: the step files, their fixtures, the runner and the Playwright config. */
const journeyInputs = [`${supportDir}/*`, `${dshxRoot}/e2e/fixtures/**`, `${dshxRoot}/playwright.e2e.config.ts`, `${dshxRoot}/scripts/run-e2e.mjs`]
/** Read by the boot gate only: it boots bundles through boot-check-web.mjs, which never loads the journey harness. */
const bootInputs = [`${dshxRoot}/scripts/boot-check-web.mjs`, `${dshxRoot}/scripts/plugin-inventory.mjs`, `${dshxRoot}/scripts/boot-ignore.json`]

/** CI changes retries; DSHX_TOOL_VERSIONS carries binaries the Host runs that no file pins (jj). */
const taskEnvironment = {
  env: ['CI', 'DSHX_TOOL_VERSIONS'],
  passThroughEnv: ['HOME', 'TMPDIR', 'USER', 'LANG', 'PLAYWRIGHT_BROWSERS_PATH', 'GITHUB_*', 'RUNNER_*'],
}

const escapeRegExp = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Cucumber expression to a whole-line RegExp, for the parameter types this suite uses. */
export const cucumberExpressionPattern = expression => {
  const parameterTypes = { string: `(?:"(?:[^"\\\\]|\\\\.)*"|'(?:[^'\\\\]|\\\\.)*')`, int: '-?\\d+', float: '-?\\d*\\.?\\d+', word: '[^\\s]+', '': '.*' }
  let pattern = ''
  for (let index = 0; index < expression.length; index += 1) {
    const character = expression[index]
    if (character === '\\' && index + 1 < expression.length) {
      pattern += escapeRegExp(expression[index + 1])
      index += 1
      continue
    }
    if (character === '{') {
      const end = expression.indexOf('}', index)
      const type = expression.slice(index + 1, end)
      if (end === -1 || !(type in parameterTypes)) return undefined
      pattern += parameterTypes[type]
      index = end
      continue
    }
    if (character === '(' || character === '/') return undefined
    pattern += escapeRegExp(character)
  }
  return new RegExp(`^${pattern}$`)
}

const unescapeStringLiteral = text =>
  text.replace(/\\(.)/g, (_, escaped) => (escaped === '\\' ? '\\' : escaped === "'" || escaped === '"' ? escaped : `\\${escaped}`))

/** Step definitions in one support file: the expression and the source text up to the next definition. */
export const parseStepDefinitions = source => {
  const starts = [...source.matchAll(/\b(?:Given|When|Then)\(\s*(['"])((?:\\.|(?!\1)[^\\])*)\1/gs)]
  return starts.map((match, index) => ({
    expression: unescapeStringLiteral(match[2]),
    body: source.slice(match.index, starts[index + 1]?.index ?? source.length),
  }))
}

/** Step lines of a feature file, keyword removed. */
export const featureSteps = source =>
  source
    .split('\n')
    .map(line => /^\s*(?:Given|When|Then|And|But|\*)\s+(.*\S)\s*$/.exec(line)?.[1])
    .filter(step => step !== undefined)

/** The package owning a feature: the one most of its `@scenario:` tags name, else the cross-plugin workspace. */
export const featureOwner = (source, packageNames) => {
  const counts = new Map()
  for (const match of source.matchAll(/@scenario:([a-z0-9-]+)\./g)) {
    const packageName = `@dshfiles/${match[1]}`
    if (packageNames.has(packageName)) counts.set(packageName, (counts.get(packageName) ?? 0) + 1)
  }
  const [owner] = [...counts.entries()].sort(([leftName, left], [rightName, right]) => right - left || leftName.localeCompare(rightName))
  return owner?.[0] ?? crossPluginOwner
}

const hasSmokeScenario = source => /^\s*@smoke\b/m.test(source)

const readJson = async path => JSON.parse(await readFile(resolve(workspaceRoot, path), 'utf8'))

const listWorkspacePackages = async () => {
  const directories = [
    ...(await readdir(resolve(workspaceRoot, 'plugins/@dshfiles'), { withFileTypes: true }))
      .filter(entry => entry.isDirectory() && existsSync(resolve(workspaceRoot, 'plugins/@dshfiles', entry.name, 'package.json')))
      .map(entry => `plugins/@dshfiles/${entry.name}`),
    `${dshxRoot}/packages/dshx`,
  ]
  const packages = new Map()
  for (const directory of directories) {
    const manifest = await readJson(`${directory}/package.json`)
    const declaredRanges = { ...manifest.dependencies, ...manifest.peerDependencies, ...manifest.devDependencies }
    const declares = Object.keys(declaredRanges)
    packages.set(manifest.name, {
      name: manifest.name,
      directory,
      isBundle: manifest.dsh !== undefined,
      usesPluginUi: declares.includes('@dshfiles/plugin-ui'),
      workspaceDependencies: declares.filter(name => typeof declaredRanges[name] === 'string' && declaredRanges[name].startsWith('workspace:')),
    })
  }
  return packages
}

export const dependencyClosure = (names, packages) => {
  const seen = new Set()
  const visit = name => {
    const workspacePackage = packages.get(name)
    if (workspacePackage === undefined || seen.has(name)) return
    seen.add(name)
    for (const dependency of workspacePackage.workspaceDependencies) visit(dependency)
  }
  for (const name of names) visit(name)
  return [...seen].sort()
}

const builtPackageInputs = (names, packages) =>
  dependencyClosure(names, packages).flatMap(name => {
    const { directory } = packages.get(name)
    return [distDigestFile(name), `${directory}/package.json`, `${directory}/cordis.patch.yml`]
  })

const runtimeDistFiles = async root => {
  const entries = await readdir(root, { recursive: true, withFileTypes: true }).catch(error => {
    if (error?.code === 'ENOENT') return []
    throw error
  })
  return entries
    .filter(entry => entry.isFile() && !/\.(map|d\.ts)$/.test(entry.name))
    .map(entry => relative(root, resolve(entry.parentPath, entry.name)))
    .sort()
}

/**
 * Digest of what a booted bundle runs. Source maps and declarations stay out: a formatting-only change to plugin-ui
 * rewrites the maps of every bundle that inlines it while their JavaScript stays byte-identical.
 */
export const runtimeDistDigest = async distRoot => {
  const hash = createHash('sha256')
  for (const file of await runtimeDistFiles(distRoot)) {
    hash.update(`${file}\0`)
    hash.update(await readFile(resolve(distRoot, file)))
    hash.update('\0')
  }
  return hash.digest('hex')
}

/**
 * Record a digest of every workspace package's runtime `dist`, the key the browser tasks read; run after building.
 * A scoped run passes the packages it just built, since a task only reads the digests of its own boot closure.
 */
export const writeDistDigests = async (input = {}) => {
  const packages = await listWorkspacePackages()
  await mkdir(resolve(workspaceRoot, distDigestDir), { recursive: true })
  const selected =
    input.names === undefined ? [...packages.values()] : input.names.flatMap(name => (packages.get(name) === undefined ? [] : [packages.get(name)]))
  for (const { name, directory } of selected) {
    const digest = await runtimeDistDigest(resolve(workspaceRoot, directory, 'dist'))
    await writeFile(resolve(workspaceRoot, distDigestFile(name)), `${digest}\n`)
  }
}

const rootAnchored = paths => [...new Set(paths)].sort().map(path => `$TURBO_ROOT$/${path}`)

const relativeImports = (source, fromFile) =>
  [...source.matchAll(/from\s+['"](\.{1,2}\/[^'"]+)['"]/g)].map(match =>
    relative(workspaceRoot, resolve(workspaceRoot, dirname(fromFile), match[1].replace(/\.js$/, '.ts'))),
  )

/** Everything a cached browser task needs, derived from the feature files, step files and package manifests. */
export const planBrowserTasks = async () => {
  const packages = await listWorkspacePackages()
  const bundleNames = [...packages.values()].filter(workspacePackage => workspacePackage.isBundle).map(workspacePackage => workspacePackage.name)
  const supportFiles = [
    ...(await readdir(resolve(workspaceRoot, supportDir)))
      .filter(name => name.endsWith('.ts') && !name.endsWith('.test.ts'))
      .map(name => `${supportDir}/${name}`),
    ...(await readdir(resolve(workspaceRoot, journeysDir))).filter(name => name.endsWith('.ts')).map(name => `${journeysDir}/${name}`),
  ]
  const sources = new Map()
  for (const file of supportFiles) sources.set(file, await readFile(resolve(workspaceRoot, file), 'utf8'))
  const definitions = supportFiles.flatMap(file =>
    parseStepDefinitions(sources.get(file)).map(definition => ({ ...definition, file, pattern: cucumberExpressionPattern(definition.expression) })),
  )
  const journeyFiles = supportFiles.filter(file => file.startsWith(`${journeysDir}/`))

  const owners = new Map()
  const featureNames = (await readdir(resolve(workspaceRoot, featuresDir))).filter(name => name.endsWith('.feature')).sort()
  for (const featureName of featureNames) {
    const featureFile = `${featuresDir}/${featureName}`
    const source = await readFile(resolve(workspaceRoot, featureFile), 'utf8')
    const ownerName = featureOwner(source, packages)
    const usedDefinitions = []
    const unmatchedSteps = []
    for (const step of featureSteps(source)) {
      const definition = definitions.find(candidate => candidate.pattern?.test(step))
      if (definition === undefined) unmatchedSteps.push(step)
      else usedDefinitions.push(definition)
    }
    const unmatched = unmatchedSteps.length > 0
    // A step no expression matched could live in any file, so the feature depends on all of them.
    const usedJourneyFiles = new Set(unmatched ? journeyFiles : usedDefinitions.map(definition => definition.file).filter(file => journeyFiles.includes(file)))
    for (const file of [...usedJourneyFiles]) {
      for (const imported of relativeImports(sources.get(file), file)) if (journeyFiles.includes(imported)) usedJourneyFiles.add(imported)
    }
    const bootsEveryBundle = unmatched || usedDefinitions.some(definition => /\bbootProfile\(/.test(definition.body))
    const mentioned = [source, ...usedDefinitions.map(definition => definition.body)].flatMap(text =>
      [...text.matchAll(/@dshfiles\/[a-z0-9-]+/g)].map(match => match[0]),
    )
    const booted = bootsEveryBundle ? bundleNames : mentioned.filter(name => packages.get(name)?.isBundle === true)

    const owner = owners.get(ownerName) ?? { name: ownerName, features: [], smokeFeatures: [], booted: new Set(), journeyFiles: new Set(), unmatchedSteps: [] }
    owner.features.push(featureName.replace(/\.feature$/, ''))
    if (hasSmokeScenario(source)) owner.smokeFeatures.push(featureName.replace(/\.feature$/, ''))
    owner.unmatchedSteps.push(...unmatchedSteps)
    for (const name of booted) owner.booted.add(name)
    // Every composed boot of a plugin-ui consumer carries the sheet owner, and a class change can change what the
    // journey asserts, so those tasks read its digest. The per-bundle boot check deliberately stays isolated.
    if (booted.some(name => packages.get(name)?.usesPluginUi === true)) owner.booted.add(sharedStylesBundle)
    for (const file of usedJourneyFiles) owner.journeyFiles.add(file)
    owners.set(ownerName, owner)
  }

  const fixtureInputsByFeature = new Map([['multi-host', ['scripts/profile-sync.ts']]])
  const e2eTask = owner => ({
    dependsOn: [],
    inputs: rootAnchored([
      ...sharedInputs,
      ...journeyInputs,
      ...owner.features.flatMap(feature => [`${featuresDir}/${feature}.feature`, ...(fixtureInputsByFeature.get(feature) ?? [])]),
      ...owner.journeyFiles,
      ...builtPackageInputs([...owner.booted, '@dshfiles/dshx'], packages),
    ]),
    outputs: [],
    ...taskEnvironment,
  })
  const bootTask = names => ({
    dependsOn: [],
    inputs: rootAnchored([...sharedInputs, ...bootInputs, ...builtPackageInputs([...names, '@dshfiles/dshx'], packages)]),
    outputs: [],
    ...taskEnvironment,
  })

  // The packages a scoped run must build and digest: a boot task reads the digests of its own boot closure, so
  // neither may reach beyond the selection. A bundle's closure and its owner's closure are unioned, because an owner
  // may boot several bundles while its boot task boots only itself.
  const closures = new Map()
  const addClosure = (name, seeds) => {
    const next = dependencyClosure(seeds, packages)
    const previous = closures.get(name)
    closures.set(name, previous === undefined ? next : [...new Set([...previous, ...next])].sort())
  }
  for (const name of bundleNames) addClosure(name, [name, '@dshfiles/dshx'])
  for (const owner of owners.values()) addClosure(owner.name, [...owner.booted, '@dshfiles/dshx'])

  const configs = new Map()
  const configFor = (name, directory) => configs.get(name) ?? configs.set(name, { directory, scripts: {}, tasks: {} }).get(name)
  for (const name of bundleNames) {
    const { directory } = packages.get(name)
    const config = configFor(name, directory)
    config.scripts['test:boot'] = 'node ../../../tooling/dshx/scripts/boot-check-web.mjs --plugin'
    config.tasks['test:boot'] = bootTask([name])
  }
  const crossPlugin = configFor(crossPluginOwner, 'plugins')
  crossPlugin.scripts['test:boot'] = 'node ../tooling/dshx/scripts/boot-check-web.mjs --composed'
  crossPlugin.tasks['test:boot'] = bootTask(bundleNames)
  for (const owner of owners.values()) {
    const directory = owner.name === crossPluginOwner ? 'plugins' : packages.get(owner.name).directory
    const runner = `node ${relative(resolve(workspaceRoot, directory), resolve(workspaceRoot, dshxRoot, 'scripts/run-e2e.mjs'))}`
    const config = configFor(owner.name, directory)
    config.scripts['test:e2e'] = runner
    config.tasks['test:e2e'] = e2eTask(owner)
    if (owner.smokeFeatures.length > 0) {
      config.scripts['test:e2e:smoke'] = `${runner} --smoke`
      config.tasks['test:e2e:smoke'] = e2eTask(owner)
    }
  }
  return { owners, configs, closures }
}

/**
 * What one browser-check invocation actually needs: the Turbo task filters to run, and the packages to build and
 * digest. A broad invocation (no names) keeps `undefined`, which means "every owned bundle".
 */
export const resolveBrowserSelection = async input => {
  const { owners, closures } = await planBrowserTasks()
  const packageFor = name => {
    if (name.startsWith('@dshfiles/') || name === 'dshfiles-plugins') return name
    const featureOwner = [...owners.values()].find(owner => owner.features.includes(name))
    if (input.mode !== 'boot' && featureOwner !== undefined) return featureOwner.name
    return `@dshfiles/${name}`
  }
  const filters = input.names.length === 0 ? ['--filter=./plugins', '--filter=./plugins/@dshfiles/*'] : input.names.map(name => `--filter=${packageFor(name)}`)
  if (input.names.length === 0) return { filters, buildTargets: undefined }

  const targets = new Set(['@dshfiles/dshx'])
  for (const name of input.names) {
    const selected = packageFor(name)
    for (const dependency of closures.get(selected) ?? [selected]) targets.add(dependency)
  }
  return { filters, buildTargets: [...targets].sort() }
}

const renderTurboConfig = tasks => `${generatedNotice}\n${JSON.stringify({ $schema: 'https://turborepo.dev/schema.json', extends: ['//'], tasks }, null, 2)}\n`

const parseTurboConfig = source => JSON.parse(source.replace(/^\s*\/\/.*$/gm, ''))

const generatedScriptNames = ['test:boot', 'test:e2e', 'test:e2e:smoke']

const sameJson = (left, right) => JSON.stringify(left) === JSON.stringify(right)

/** Compare (or with `write`, rewrite) each package's turbo.json and browser scripts against the plan. */
const syncConfigs = async ({ write }) => {
  const { configs } = await planBrowserTasks()
  const drift = []
  const written = []
  for (const [name, config] of configs) {
    const turboFile = resolve(workspaceRoot, config.directory, 'turbo.json')
    const current = existsSync(turboFile) ? await readFile(turboFile, 'utf8') : undefined
    const expected = renderTurboConfig(config.tasks)
    if (current === undefined || !sameJson(parseTurboConfig(current).tasks, config.tasks)) {
      drift.push(`${config.directory}/turbo.json`)
      if (write) {
        await writeFile(turboFile, expected)
        written.push(turboFile)
      }
    }
    const manifestFile = resolve(workspaceRoot, config.directory, 'package.json')
    const manifest = JSON.parse(await readFile(manifestFile, 'utf8'))
    const scripts = { ...manifest.scripts }
    for (const scriptName of generatedScriptNames) delete scripts[scriptName]
    Object.assign(scripts, config.scripts)
    if (!sameJson(scripts, manifest.scripts)) {
      drift.push(`${config.directory}/package.json scripts (${name})`)
      if (write) {
        await writeFile(manifestFile, `${JSON.stringify({ ...manifest, scripts }, null, 2)}\n`)
        written.push(manifestFile)
      }
    }
  }
  for (const entry of await readdir(resolve(workspaceRoot, 'plugins/@dshfiles'), { withFileTypes: true })) {
    const directory = `plugins/@dshfiles/${entry.name}`
    if (!entry.isDirectory() || [...configs.values()].some(config => config.directory === directory)) continue
    if (existsSync(resolve(workspaceRoot, directory, 'turbo.json'))) drift.push(`${directory}/turbo.json is stale: the package owns no browser task`)
  }
  if (written.length > 0) {
    const formatted = spawnSync('pnpm', ['exec', 'oxfmt', '--config', '.oxfmtrc.json', ...written], { cwd: workspaceRoot, stdio: 'inherit' })
    if (formatted.status !== 0) throw new Error('oxfmt could not format the generated browser task configs.')
  }
  return drift
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write')
  const drift = await syncConfigs({ write })
  if (write) console.log(drift.length === 0 ? 'Browser task configs already up to date.' : `Rewrote:\n  ${drift.join('\n  ')}`)
  else if (drift.length > 0) {
    console.error(`Browser task configs drifted from the feature files; run node tooling/dshx/scripts/browser-tasks.mjs --write:\n  ${drift.join('\n  ')}`)
    process.exitCode = 1
  } else console.log('Browser task configs match the feature files.')
}
